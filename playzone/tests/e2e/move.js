// Vérifie que le personnage avance (Z/W), saute (Espace) et ne traverse pas les murs.
import { staticServer, launch, watchConsole, sleep } from './lib.js';
const { srv, url } = await staticServer();
const { browser, context } = await launch();
const page = await context.newPage();
const errors = watchConsole(page);
await page.addInitScript(() => localStorage.setItem('playzone.save.v1', JSON.stringify({ v: 1, id: 'solo-t', name: 'Testeur', createdAt: 0, coins: 300, xp: 0, rep: 0, appearance: {} })));
await page.goto(url + 'index.html?heure=12&auto=solo');
await sleep(5000);
const frames = await page.evaluate(() => new Promise((r) => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 2000) requestAnimationFrame(f); else r(n / 2); }; requestAnimationFrame(f); }));
console.log('images/s réelles (rendu logiciel, sans GPU) :', frames);
const step = (s) => page.evaluate((s) => window.playzone.debugStep(s), s);
const pos = () => page.evaluate(() => ({ ...window.playzone.player.pos }));
const p0 = await pos();
await page.keyboard.down('KeyW'); await step(1); await page.keyboard.up('KeyW');
const p1 = await pos();
await page.keyboard.down('Space'); await step(0.25); await page.keyboard.up('Space');
const pj = (await pos()).y;
await step(1.5);
const pl = (await pos()).y;
await page.evaluate(() => { const g = window.playzone; g.player.teleport(-20, -30, Math.PI); g.cam.yaw = 0; });
await page.keyboard.down('KeyW'); await step(3); await page.keyboard.up('KeyW');
const pw = await pos();
await page.evaluate(() => { const g = window.playzone; g.player.teleport(0, 12, 0); g.cam.yaw = Math.PI; });
await page.keyboard.down('ShiftLeft'); await page.keyboard.down('KeyW'); await step(1); await page.keyboard.up('KeyW'); await page.keyboard.up('ShiftLeft');
const ps = await pos();
console.log('après 1 s de marche : avancé de', (p0.z - p1.z).toFixed(2), 'm');
console.log('après 1 s de sprint : avancé de', (ps.z - 12).toFixed(2), 'm');
console.log('hauteur pendant le saut', pj.toFixed(2), '/ après atterrissage', pl.toFixed(2));
console.log('contre la mairie (façade à z=-35) : z =', pw.z.toFixed(2));
const ok = p0.z - p1.z > 4 && ps.z - 12 > 7 && pj > 1 && Math.abs(pl) < 0.01 && pw.z > -35.1 && pw.z < -34;
console.log(ok ? 'OK : déplacement, sprint, saut et collision fonctionnent' : 'ÉCHEC');
console.log(errors.length ? errors.join('\n') : 'Aucune erreur console');
await browser.close(); srv.close();
process.exit(ok ? 0 : 1);
