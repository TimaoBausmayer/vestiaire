// Étape 2 : écran titre -> création du personnage -> bonus du jour -> boutique -> achat -> équipement.
import { staticServer, launch, watchConsole, sleep } from './lib.js';
const { srv, url } = await staticServer();
const { browser, context } = await launch();
const page = await context.newPage();
const errors = watchConsole(page);
await page.goto(url + 'index.html?heure=12');
await sleep(4500);
await page.screenshot({ path: 'tests/e2e/out/s2-title.png' });
await page.getByText('Jouer en solo').click();
await sleep(1500);
await page.getByRole('button', { name: 'Cheveux' }).click();
await page.getByRole('button', { name: 'Afro' }).click();
await page.getByRole('button', { name: 'Corps' }).click();
await page.getByPlaceholder('Ton pseudo').fill('Testeur');
await sleep(800);
await page.screenshot({ path: 'tests/e2e/out/s2-creator.png' });
await page.getByRole('button', { name: "C'est parti !" }).click();
await sleep(2500);
const p1 = await page.evaluate(() => ({ coins: window.playzone.profile.coins, name: window.playzone.profile.name }));
console.log('profil créé :', p1);
// aller à la boutique de vêtements
await page.evaluate(() => { const g = window.playzone; const b = { x: -18, z: 34.5 }; g.player.teleport(b.x, b.z, 0); g.cam.yaw = Math.PI; });
await page.evaluate(() => window.playzone.debugStep(0.3));
const prompt = await page.locator('.prompt').textContent();
console.log('invite :', prompt);
await page.keyboard.press('KeyE');
await sleep(800);
await page.screenshot({ path: 'tests/e2e/out/s2-shop.png' });
await page.locator('.card', { hasText: 'Casquette Rouge Vif' }).getByRole('button', { name: 'Acheter' }).click();
await sleep(800);
const p2 = await page.evaluate(() => ({ coins: window.playzone.profile.coins, hat: window.playzone.profile.appearance.hat, inv: window.playzone.profile.inventory }));
console.log('après achat :', p2);
await page.keyboard.press('Escape');
await sleep(400);
await page.evaluate(() => { const g = window.playzone; g.cam.yaw = 0; g.cam.dist = 4; g.cam.pitch = 0.2; g.debugStep(0.5); });
await sleep(800);
await page.screenshot({ path: 'tests/e2e/out/s2-equipped.png' });
const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('playzone.save.v1')).appearance.hat);
console.log('chapeau sauvegardé dans localStorage :', saved);
const ok = p1.coins === 250 && p2.coins === 190 && p2.hat === 'casquette' && saved === 'casquette';
console.log(ok ? 'OK' : 'ÉCHEC');
console.log(errors.length ? errors.join('\n') : 'Aucune erreur console');
await browser.close(); srv.close();
process.exit(ok ? 0 : 1);
